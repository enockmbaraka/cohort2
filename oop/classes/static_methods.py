#!/usr/bin/python3

class mathsfunctions:
    @staticmethod
    def mul(a , b):
        prod = a * b
        return prod

    @staticmethod
    def div(a, b):
        quotient = a / b
        return quotient

    @staticmethod
    def add(a, b):
        addition = a + b
        return addition

    @staticmethod
    def sub(a, b):
        result = a - b
        return result
    @staticmethod
    def exp(a, b):
        expon = a ** b
        return expon
